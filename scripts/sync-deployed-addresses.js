/**
 * sync-deployed-addresses.js
 *
 * Reads contracts/deployments/local.json and synchronizes the contract
 * addresses across:
 * 1. backend/.env
 * 2. scripts/.deployed_env (for shell export in container startup scripts)
 */

const fs = require('fs');
const path = require('path');

const localDeploymentPath = path.resolve(__dirname, '../contracts/deployments/local.json');
const backendEnvPath = path.resolve(__dirname, '../backend/.env');
const shellEnvPath = path.resolve(__dirname, '.deployed_env');

if (!fs.existsSync(localDeploymentPath)) {
  console.error(`[sync-deployed-addresses] Error: Deployment file not found at ${localDeploymentPath}`);
  process.exit(1);
}

let deployment;
try {
  deployment = JSON.parse(fs.readFileSync(localDeploymentPath, 'utf-8'));
} catch (err) {
  console.error('[sync-deployed-addresses] Failed to parse local.json:', err.message);
  process.exit(1);
}

const registryAddress = deployment?.contracts?.Registry?.address;
const certificateRegistryAddress = deployment?.contracts?.CertificateRegistry?.address;

if (!registryAddress || !certificateRegistryAddress) {
  console.error('[sync-deployed-addresses] Missing Registry or CertificateRegistry in deployment JSON.');
  process.exit(1);
}

console.log('----------------------------------------------------');
console.log('Contract Address Synchronization:');
console.log(`  Registry:            ${registryAddress}`);
console.log(`  CertificateRegistry: ${certificateRegistryAddress}`);
console.log('----------------------------------------------------');

// 1. Update / Create backend/.env
let envContent = '';
if (fs.existsSync(backendEnvPath)) {
  envContent = fs.readFileSync(backendEnvPath, 'utf-8');
}

function updateEnvVar(content, key, value) {
  const regex = new RegExp(`^${key}=.*$`, 'm');
  if (regex.test(content)) {
    return content.replace(regex, `${key}=${value}`);
  }
  return content ? `${content.trim()}\n${key}=${value}\n` : `${key}=${value}\n`;
}

envContent = updateEnvVar(envContent, 'REGISTRY_CONTRACT_ADDRESS', registryAddress);
envContent = updateEnvVar(envContent, 'CERTIFICATE_REGISTRY_CONTRACT_ADDRESS', certificateRegistryAddress);

// Ensure default RPC and operator key are present if missing
if (!envContent.includes('BLOCKCHAIN_RPC_URL=')) {
  envContent = updateEnvVar(envContent, 'BLOCKCHAIN_RPC_URL', 'http://127.0.0.1:8545');
}
if (!envContent.includes('OPERATOR_PRIVATE_KEY=')) {
  envContent = updateEnvVar(envContent, 'OPERATOR_PRIVATE_KEY', '0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80');
}

fs.writeFileSync(backendEnvPath, envContent, 'utf-8');
console.log(`✔ Updated backend/.env successfully.`);

// 2. Write scripts/.deployed_env for shell scripting
const shellContent = `# Auto-generated by sync-deployed-addresses.js
export REGISTRY_CONTRACT_ADDRESS=${registryAddress}
export CERTIFICATE_REGISTRY_CONTRACT_ADDRESS=${certificateRegistryAddress}
export BLOCKCHAIN_RPC_URL=http://127.0.0.1:8545
export OPERATOR_PRIVATE_KEY=\${OPERATOR_PRIVATE_KEY:-0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80}
`;

fs.writeFileSync(shellEnvPath, shellContent, 'utf-8');
console.log(`✔ Generated scripts/.deployed_env for shell processes.`);
